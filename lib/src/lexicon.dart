/// One word, stem or phrase, with the language it belongs to and the lowest strictness that turns it on.
class LexiconEntry {
  final String text;
  final Language language;
  final Strictness strictness;

  const LexiconEntry(this.text, this.language, this.strictness);

  @override
  String toString() => 'LexiconEntry($text, ${language.name}, ${strictness.name})';
}

List<LexiconEntry> _tag(Language language, Strictness strictness, List<String> texts) =>
    [for (final text in texts) LexiconEntry(text, language, strictness)];

