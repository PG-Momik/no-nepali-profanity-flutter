List<String> _texts(List<LexiconEntry> entries, {required bool latin}) => List.unmodifiable([
      for (final e in entries)
        if ((e.language != Language.devanagari) == latin) e.text
    ]);

/// Every Latin-script word, at every strictness.
final List<String> latinWords = _texts(words, latin: true);

/// Every Latin-script stem, at every strictness.
